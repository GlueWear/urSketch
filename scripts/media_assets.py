"""Build authenticated, content-addressed local media for the Gall HTTP handler."""
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MIMES = {'.mp4':'video/mp4','.mp3':'audio/mpeg','.jpg':'image/jpeg','.png':'image/png','.ogg':'audio/ogg','.wav':'audio/wav','.webm':'video/webm','.svg':'image/svg+xml'}

def media_assets():
    assets = {}
    for path in sorted((ROOT/'desk/media').rglob('*')):
        if path.suffix.lower() not in MIMES: continue
        data = path.read_bytes()
        digest = hashlib.sha256(data).hexdigest()
        name = path.relative_to(ROOT/'desk/media').as_posix()
        assets[name] = {'url':f'/apps/ursketch/media/{digest[:16]}/{name}','mime':MIMES[path.suffix.lower()],'bytes':len(data),'sha256':digest,'data':data}
    return assets

def write_media(assets):
    lines = ['::  Generated by scripts/build.py; binary assets live under desk/media/.','|%','++  lookup','  |=  url=@t','  ^-  (unit [mime=@t etag=@t file=path])']
    for name,asset in assets.items():
        parts = ['media',*name.rsplit('.',1)[0].split('/'),name.rsplit('.',1)[1]]
        path = '/' + '/'.join("['"+part+"']" for part in parts)
        lines.extend([f"  ?:  =(url '{asset['url']}')",f"    `['{asset['mime']}' '\"{asset['sha256']}\"' {path}]"])
    lines += ['  ~','--','']
    (ROOT/'desk/lib/ursketch-media.hoon').write_text('\n'.join(lines))
